#!/usr/bin/env python3
"""Generate Folio's offline single-character Mandarin search table.

Input: official Unicode 17.0.0 Unihan.zip, downloaded separately from
https://www.unicode.org/Public/17.0.0/ucd/Unihan.zip
Data copyright/permission: Unicode License v3, licenses/Unicode-3.0.txt.
No dictionary or firmware application implementation is copied. kMandarin's
first listed pronunciation is used: this is not phrase/polyphone recognition.
"""
import argparse
import hashlib
from pathlib import Path
import unicodedata
import zipfile

EXPECTED_SHA256 = "f7a48b2b545acfaa77b2d607ae28747404ce02baefee16396c5d2d7a8ef34b5e"


def normalize(reading: str) -> str:
    decomposed = unicodedata.normalize("NFD", reading.lower())
    # Preserve the vowel distinction while dropping tone accents.
    decomposed = decomposed.replace("u\u0308", "v")
    return "".join(c for c in decomposed if not unicodedata.combining(c))


def generate(source: Path, target: Path) -> None:
    digest = hashlib.sha256(source.read_bytes()).hexdigest()
    if digest != EXPECTED_SHA256:
        raise ValueError("Input is not the pinned official Unicode 17.0.0 Unihan.zip")
    with zipfile.ZipFile(source) as archive:
        text = archive.read("Unihan_Readings.txt").decode("utf-8")
    readings = {}
    for line in text.splitlines():
        if not line or line.startswith("#"):
            continue
        cp, key, value = line.split("\t")
        if key != "kMandarin":
            continue
        reading = normalize(value.split()[0])
        if not reading or len(reading) > 6 or any(c not in "abcdefghijklmnopqrstuvwxyz" for c in reading):
            raise ValueError(f"Unsupported kMandarin reading: {line}")
        readings[int(cp[2:], 16)] = reading
    syllables = sorted(set(readings.values()))
    if len(syllables) > 512 or not readings:
        raise ValueError("Unexpected syllable count")
    ids = {syllable: index for index, syllable in enumerate(syllables)}
    output = ["// Generated by tools/generate_pinyin.py; do not edit.",
              "// Unicode 17.0.0 Unihan kMandarin; Unicode License v3.",
              "// Data copyright 2025 Unicode, Inc.; see licenses/Unicode-3.0.txt.",
              "// Source: https://www.unicode.org/Public/17.0.0/ucd/Unihan.zip",
              f"// Source SHA-256: {digest}",
              "// One default reading per character; tone accents removed, ü -> v.",
              "// Packed word: Unicode scalar << 9 | syllable index.",
              "static const char catalog_pinyin_syllables[][7] = {"]
    output += [f'    "{syllable}",' for syllable in syllables]
    output += ["};", "static const uint32_t catalog_pinyin_map[] = {"]
    packed = [(cp << 9) | ids[readings[cp]] for cp in sorted(readings)]
    for start in range(0, len(packed), 8):
        output.append("    " + ", ".join(f"0x{value:08x}u" for value in packed[start:start + 8]) + ",")
    output += ["};", ""]
    target.write_text("\n".join(output))
    print(f"{len(readings)} characters, {len(syllables)} syllables, {len(packed)*4+len(syllables)*7} flash bytes")
    print(f"Unihan.zip SHA-256: {digest}")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("unihan_zip", type=Path)
    parser.add_argument("output", type=Path, nargs="?", default=Path("main/book/folio_pinyin_table.inc"))
    args = parser.parse_args()
    generate(args.unihan_zip, args.output)
