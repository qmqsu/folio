#!/usr/bin/env python3
"""Generate the GBK code-point lookup table from Python's standard codec."""

from pathlib import Path


def main() -> None:
    trails = [*range(0x40, 0x7F), *range(0x80, 0xFF)]
    values: list[int] = []
    for lead in range(0x81, 0xFF):
        for trail in trails:
            try:
                decoded = bytes((lead, trail)).decode("gbk", errors="strict")
                values.append(ord(decoded) if len(decoded) == 1 else 0)
            except UnicodeDecodeError:
                values.append(0)

    target = Path(__file__).resolve().parents[1] / "main" / "book" / "folio_gbk_table.c"
    rows = [
        "/* Generated by tools/gen_gbk_table.py using Python's standard GBK codec. */",
        '#include "folio_gbk_table.h"',
        "",
        "const uint16_t folio_gbk_table[126 * 190] = {",
    ]
    for start in range(0, len(values), 12):
        rows.append("    " + ", ".join(f"0x{value:04x}" for value in values[start : start + 12]) + ",")
    rows.extend(("};", ""))
    target.write_text("\n".join(rows), encoding="utf-8")


if __name__ == "__main__":
    main()
